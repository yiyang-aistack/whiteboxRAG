    // ==================== 状态管理 ====================
    /** 根据浏览器语言偏好推断默认语言（仅在 localStorage 无记录时生效） */
    function detectDefaultLang() {
        try {
            const nav = (navigator.languages && navigator.languages[0]) || navigator.language || '';
            return /^en/i.test(nav) ? 'en-US' : 'zh-CN';
        } catch (e) {
            return 'zh-CN';
        }
    }
    let currentLang = localStorage.getItem('lang') || detectDefaultLang();

    /**
     * 获取当前语言
     */
    function getLang() {
        return currentLang;
    }

    /**
     * 设置语言并持久化
     */
    function setLang(lang) {
        if (!translations[lang]) return;
        currentLang = lang;
        localStorage.setItem('lang', lang);
        applyI18n();
        // 更新语言切换按钮显示
        updateLangButton();
        // 触发语言变更事件，供页面自定义逻辑监听
        document.dispatchEvent(new CustomEvent('langChanged', { detail: { lang: lang } }));
    }

    /**
     * 切换语言（中英切换）
     */
    function toggleLang() {
        setLang(currentLang === 'zh-CN' ? 'en-US' : 'zh-CN');
    }

    /**
     * 翻译函数
     * @param {string} key - 翻译键
     * @param {string} [lang] - 可选语言，默认当前语言
     * @returns {string} 翻译文本，找不到则返回 key
     */
    function t(key, paramsOrLang, lang) {
        let l = lang || currentLang;
        let params = null;
        if (typeof paramsOrLang === 'string') {
            l = paramsOrLang;
        } else if (paramsOrLang && typeof paramsOrLang === 'object') {
            params = paramsOrLang;
        }
        let dict = translations[l] || translations['zh-CN'];
        let result = dict[key] || translations['zh-CN'][key] || key;
        if (params) {
            for (const pk in params) {
                result = result.replace(new RegExp('\\{' + pk + '\\}', 'g'), params[pk]);
            }
        }
        return result;
    }

    /**
     * 批量翻译函数 - 用于 JS 中构建 HTML
     * @param {string} key
     * @param {Object} [params] Optional placeholder values
     * @returns {string}
     */
    function tt(key, params) {
        return t(key, params);
    }

